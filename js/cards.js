export const MIRROR = v => 7 - v;

export function matches(req, dice) {
  if (!dice) return false;
  const c = [0, 0, 0, 0, 0, 0, 0];
  for (const d of dice) c[d]++;
  if (req[0] === 'R') {
    const k = +req[1];
    for (let s = 1; s + k - 1 <= 6; s++) {
      let ok = true;
      for (let v = s; v < s + k; v++) if (!c[v]) { ok = false; break; }
      if (ok) return true;
    }
    return false;
  }
  let S = 0, M = 0;
  for (const ch of req) {
    if (ch === 'S') S++;
    else if (ch === 'M') M++;
    else if (--c[+ch] < 0) return false;
  }
  if (!S && !M) return true;
  for (let sv = 1; sv <= 6; sv++) {
    if (c[sv] < S) continue;
    if (!M) return true;
    c[sv] -= S;
    for (let mv = 1; mv <= 6; mv++) if (c[mv] >= M) { c[sv] += S; return true; }
    c[sv] += S;
  }
  return false;
}

// Описание требования словами — для подсказки.
export function reqText(req) {
  if (req === 'R4') return 'четыре значения подряд';
  if (req === 'R5') return 'пять значений подряд';
  const fixed = req.replace(/[SM]/g, '');
  const S = (req.match(/S/g) || []).length, M = (req.match(/M/g) || []).length;
  const parts = [];
  if (fixed) parts.push(fixed.split('').join('-'));
  const same = n => ({ 2: 'пара', 3: 'тройка', 4: 'каре', 5: 'пять одинаковых' }[n]);
  if (S && M) parts.push(`${same(S)} + ${same(M)}`);
  else if (S) parts.push(S === 1 ? 'любой кубик' : (fixed ? 'и ещё ' : '') + same(S) + ' любых');
  return parts.join(' ');
}
